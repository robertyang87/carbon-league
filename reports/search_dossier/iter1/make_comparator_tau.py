def body_after_imports(path):
    """File content after the module docstring and top-level imports,
    with any top-level __all__ assignment and trailing __main__ block
    removed (the assembly provides its own)."""
    src = open(path, encoding="utf-8").read()
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)
    cut = 0
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            cut = max(cut, node.end_lineno)
        elif isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "__all__"
                for t in node.targets):
            cut = max(cut, node.end_lineno)
        elif isinstance(node, ast.If) and "__main__" in ast.dump(node.test):
            # trailing self-test runner: drop from its first line on
            return "".join(lines[cut:node.lineno - 1])
    return "".join(lines[cut:])


def main():
    src_dir, out = sys.argv[1], sys.argv[2]
    texts = {}
    for name, want in PIN.items():
        raw = open(os.path.join(src_dir, name), "rb").read()
        got = hashlib.md5(raw).hexdigest()
        assert got == want, f"{name} md5 mismatch: {got} != {want}"
        texts[name] = raw.decode("utf-8")

    kernel = body_after_imports(os.path.join(src_dir, "comparator.py"))
    kernel = kernel.replace("def _self_test()", "def _kernel_self_test()")
    telemetry = body_after_imports(os.path.join(src_dir, "telemetry.py"))
    adapters = body_after_imports(os.path.join(src_dir, "leaf_adapters.py"))

    header = HEADER.format(
        md5_kernel=PIN["comparator.py"],
        md5_telemetry=PIN["telemetry.py"],
        md5_adapters=PIN["leaf_adapters.py"])
    module = (header
              + "\n\n# " + "=" * 67 + "\n"
              + "# Comparator kernel (iter1 variant prototype comparator.py, verbatim)\n"
              + "# " + "=" * 67 + "\n"
              + kernel.strip("\n") + "\n\n\n"
              + "# " + "=" * 67 + "\n"
              + "# Telemetry (frozen prototype telemetry.py, verbatim)\n"
              + "# " + "=" * 67 + "\n"
              + telemetry.strip("\n") + "\n\n\n"
              + "# " + "=" * 67 + "\n"
              + "# Leaf adapters (frozen prototype leaf_adapters.py, verbatim)\n"
              + "# " + "=" * 67 + "\n"
              + adapters.strip("\n") + "\n")
    with open(out, "w", encoding="utf-8") as f:
        f.write(module)
    md5 = hashlib.md5(module.encode("utf-8")).hexdigest()
    print(f"wrote {out}: {len(module)} chars, md5 {md5}")

    # ---- self-proof checklist (against the generated module) ---------
    spec = importlib.util.spec_from_file_location("cnet2_comparator_gen", out)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["cnet2_comparator_gen"] = mod
    spec.loader.exec_module(mod)
    proof = {}

    def check(name, fn):
        try:
            fn()
            proof[name] = "PASS"
        except Exception as e:  # noqa: BLE001
            proof[name] = f"FAIL: {e!r}"

    C = mod.Candidate
    cands = [C(index=0, action="a0", is_a0=True),
             C(index=1, action="a1", is_a0=False),
             C(index=2, action="a2", is_a0=False)]
    vals = {"a0": 0.5, "a1": 0.8, "a2": 0.65}
    ro = lambda s, a, h, seed: a          # noqa: E731
    lf = lambda ls: vals[ls]              # noqa: E731

    def p_kernel_entries():
        assert hasattr(mod.Comparator, "decide")
        assert hasattr(mod.Comparator, "decide_multi")
        d = mod.Comparator(1.0).decide(None, cands, ro, lf, 1, 42)
        assert d.chosen_index == 1 and d.completed_rounds == 1
    check("kernel_decide_and_decide_multi_present", p_kernel_entries)

    def p_finiteness():
        bad = dict(vals); bad["a1"] = float("inf")
        d = mod.Comparator(1.0).decide(None, cands, ro, lambda ls: bad[ls], 1, 42)
        assert d.completed_rounds == 0 and d.chosen_index == 0
        assert d.abort_reason == "nonfinite_leaf"
        bad2 = dict(vals); bad2["a0"] = float("nan")
        d2 = mod.Comparator(1.0).decide(None, cands, ro, lambda ls: bad2[ls], 1, 42)
        assert d2.completed_rounds == 0 and d2.abort_reason == "nonfinite_leaf"
    check("finiteness_gate_inf_nan", p_finiteness)

    def p_anytime():
        # H1 changes, H2 raises inside rollout -> H1 result retained.
        def ro2(s, a, h, seed):
            if h == 2:
                raise RuntimeError("boom")
            return a
        d = mod.Comparator(1.0).decide_multi(None, cands, ro2, lf, [1, 2], 42)
        assert d.completed_rounds == 1 and d.chosen_index == 1
        assert d.abort_reason == "exception"
    check("anytime_retains_previous_round", p_anytime)

    def p_chi_admission():
        calls = {"n": 0}
        def ro3(s, a, h, seed):
            calls["n"] += 1
            return a
        d = mod.Comparator(1.0).decide(None, cands, ro3, lf, 1, 42,
                                       est_candidate_cost_s=10.0)
        assert d.completed_rounds == 0 and d.abort_reason == "budget_gate"
        assert calls["n"] == 0
        d2 = mod.Comparator(1.0).decide(None, cands, ro3, lf, 1, 42,
                                        est_candidate_cost_s=None)
        assert d2.completed_rounds == 1  # cold start: waived, still runs
    check("c_hi_admission_and_cold_start", p_chi_admission)

    def p_deadline_abs():
        import time as _t
        d = mod.Comparator(5.0).decide(None, cands, ro, lf, 1, 42,
                                       deadline_abs=_t.monotonic() - 1.0)
        assert d.completed_rounds == 0 and d.chosen_index == 0
        assert d.abort_reason in ("deadline", "single_call_overrun")
    check("deadline_abs_no_topup", p_deadline_abs)

    def p_phase_telemetry():
        sc = mod.StatsCollector()
        sc.record_decision({"completed": True, "rounds": 1, "changed": True,
                            "depth": 1, "leaf_calls": 3, "cost_s": 0.01,
                            "total_cost_s": 0.30,
                            "phase_costs": {"pre_cmp": 0.29, "compare": 0.01},
                            "abort_reason": None})
        snap = sc.snapshot()
        assert snap["total_cost_accum_s"] == 0.30
        assert abs(snap["phase_cost_accum_s"]["pre_cmp"] - 0.29) < 1e-12
        assert snap["completed_comparisons"] == 1 and snap["leaf_calls"] == 3
    check("phase_and_total_telemetry", p_phase_telemetry)

    def p_tau_threshold():
        # a1's advantage over a0 is 0.80 - 0.50 = 0.30.
        d = mod.Comparator(1.0, tau=0.5).decide(None, cands, ro, lf, 1, 42)
        assert d.chosen_index == 0 and d.changed is False
        assert d.completed_rounds == 1 and d.completed_comparisons == 3
        d2 = mod.Comparator(1.0, tau=0.2).decide(None, cands, ro, lf, 1, 42)
        assert d2.chosen_index == 1 and d2.changed is True
        d3 = mod.Comparator(1.0, tau=150.0).decide_multi(
            None, cands, ro, lf, [1], 42)
        assert d3.chosen_index == 0 and d3.completed_rounds == 1
        d4 = mod.Comparator(1.0).decide(None, cands, ro, lf, 1, 42)
        assert d4.chosen_index == 1 and d4.changed is True  # tau=0 default
    check("tau_commit_threshold", p_tau_threshold)

    def p_adapter_finiteness():
        va = mod.VNetLeafAdapter(checkpoint=33, state_md5="x",
                                 backend=lambda s: float("inf"))
        out = va(None)
        assert out == float("inf") and va.nonfinite_count == 1  # NOT 1.0
        ha = mod.HeuristicLeafAdapter(lambda s: float("nan"))
        out2 = ha(None)
        assert out2 != out2 and ha.nonfinite_count == 1  # NaN passes through
    check("adapter_finiteness_before_tanh", p_adapter_finiteness)

    proof["module_md5"] = md5
    proof["source_md5"] = dict(PIN)
    with open(out + ".proof.json", "w") as f:
        json.dump(proof, f, indent=1)
    print(json.dumps(proof, indent=1))
    assert all(v == "PASS" for k, v in proof.items() if k not in
               ("module_md5", "source_md5")), "SELF-PROOF FAILED"


if __name__ == "__main__":
    main()
