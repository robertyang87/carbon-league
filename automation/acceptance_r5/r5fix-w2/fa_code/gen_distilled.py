#!/usr/bin/env python3
"""gen_distilled -- assemble the deployable distilled policy files.

distilled_v1.py        (plan A: pure NN, SHIELDS = False)
distilled_v1_hybrid.py (plan B: NN + hard-rule shields, SHIELDS = True)

Assembly (both files identical except the SHIELDS flag):
  header + SIZE/N constants
  base_v53.py lines 286-551 verbatim: _rc, NB/NB8/DIST/N1/N2 tables,
    CLS/CLS_MEMBERS, REGEN/CAP/ABS/COLLECT constants, apply_ops, and
    the Belief class -- the teacher's own belief machinery, so the
    deployed policy maintains the exact estimate grid it was
    distilled on.
  distill_features.py verbatim (the featurizer the training data
    was built with).
  SHIELDS = True/False
  distill_actor_src.py verbatim (tracker + sampling protocol +
    shields + agent/make_agent entry points).
Weights live in distilled_v1_weights.npz next to the policy file.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = '''"""distilled_v1 -- Case-B stage 1: base_v53 distilled into an NN
policy (worker/base MLP heads over the teacher's own Belief estimate).

Generated by gen_distilled.py -- do not edit by hand; edit
distill_features.py / distill_actor_src.py and regenerate.
SHIELDS = {shields}: False = pure NN (plan A); True = NN + hard-rule
shields (plan B: collision-safety mask, endgame return, base-mouth
integration, cash-chain rescue).
"""
import numpy as np

SIZE = 15
N = SIZE * SIZE

'''


def main():
    base_lines = (HERE / "base_v53.py").read_text().splitlines()
    belief_chunk = "\n".join(base_lines[285:551]) + "\n"
    features = (HERE / "distill_features.py").read_text()
    actor = (HERE / "distill_actor_src.py").read_text()
    for shields, fname in ((False, "distilled_v1.py"),
                           (True, "distilled_v1_hybrid.py")):
        text = (HEADER.format(shields=shields)
                + belief_chunk
                + "\n\n" + features
                + f"\n\nSHIELDS = {shields}\n"
                + actor)
        out = HERE / fname
        out.write_text(text)
        print(f"wrote {out} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
